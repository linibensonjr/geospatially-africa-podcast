-- Geospatially Africa: Supabase schema
-- Run this once in Supabase Dashboard → SQL Editor.

create table if not exists public.hosts (
  id bigint generated by default as identity primary key,
  name text not null unique,
  role text,
  bio text not null default '',
  image text,
  location text,
  linkedin text,
  twitter text
);

create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null unique
);

create table if not exists public.episodes (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  summary text not null default '',
  description text not null default '',
  transcript text,
  season integer,
  episode integer,
  published_date timestamptz,
  host text,
  cohost text,
  guest text,
  guest_bio text,
  guest_image text,
  episode_image text,
  link text,
  audio_url text,
  spotify text,
  applepodcast text,
  youtube text,
  chapters text,
  links_mentioned text,
  created_at timestamptz not null default now()
);

create table if not exists public.episode_tags (
  episode_id bigint not null references public.episodes(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (episode_id, tag_id)
);

create table if not exists public.subscribers (
  id bigint generated by default as identity primary key,
  name text,
  email text not null unique,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint subscribers_email_not_blank check (length(trim(email)) > 3)
);

alter table public.episodes add column if not exists audio_url text;
alter table public.episodes add column if not exists transcript text;
alter table public.subscribers add column if not exists name text;

create index if not exists episodes_published_date_idx
  on public.episodes (published_date desc);
create index if not exists episodes_host_idx on public.episodes (host);
create index if not exists episodes_cohost_idx on public.episodes (cohost);
create index if not exists episode_tags_tag_id_idx on public.episode_tags (tag_id);

alter table public.episodes enable row level security;
alter table public.hosts enable row level security;
alter table public.tags enable row level security;
alter table public.episode_tags enable row level security;
alter table public.subscribers enable row level security;

drop policy if exists "Public can read episodes" on public.episodes;
create policy "Public can read episodes"
  on public.episodes for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can read hosts" on public.hosts;
create policy "Public can read hosts"
  on public.hosts for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can read tags" on public.tags;
create policy "Public can read tags"
  on public.tags for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can read episode tags" on public.episode_tags;
create policy "Public can read episode tags"
  on public.episode_tags for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can subscribe" on public.subscribers;
create policy "Public can subscribe"
  on public.subscribers for insert
  to anon, authenticated
  with check (is_active = true);

grant usage on schema public to anon, authenticated;
grant select on public.episodes, public.hosts, public.tags, public.episode_tags
  to anon, authenticated;
grant insert on public.subscribers to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

revoke select, update, delete on public.subscribers from anon, authenticated;
revoke insert, update, delete on public.episodes, public.hosts, public.tags,
  public.episode_tags from anon, authenticated;
